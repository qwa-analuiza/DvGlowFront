-- Rode este script em: Supabase > SQL Editor > New query > Run
-- Se a sua tabela "produtos" já existe, o create table é ignorado e só as permissões são aplicadas.

create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text not null,
  preco numeric(10,2) not null,
  imagem text not null
);

-- Permissões da tabela: qualquer pessoa lê, só o admin logado altera
alter table public.produtos enable row level security;

drop policy if exists "leitura publica" on public.produtos;
create policy "leitura publica" on public.produtos
  for select using (true);

drop policy if exists "admin altera produtos" on public.produtos;
create policy "admin altera produtos" on public.produtos
  for all to authenticated
  using (true) with check (true);

-- Bucket público para as fotos dos produtos
insert into storage.buckets (id, name, public)
values ('produtos', 'produtos', true)
on conflict (id) do update set public = true;

drop policy if exists "admin altera imagens" on storage.objects;
create policy "admin altera imagens" on storage.objects
  for all to authenticated
  using (bucket_id = 'produtos') with check (bucket_id = 'produtos');
